// Keyword-based emoji suggestion for a material name (Ukrainian/Russian
// construction terms). Best-effort; always editable by the user afterward.
const RULES = [
  [/дошк|брус|балк|рейк|фанер|OSB|осб|стропил|каркас|деревян|дерев'ян/i, "🪵"],
  [/цвях|шуруп|саморіз|болт|гайк|кріплен|метиз/i, "🔩"],
  [/утеплюв|мінват|пінопласт|penoplex|пеноплекс|ізоляц/i, "🧱"],
  [/цемент|бетон|розчин|штукатур/i, "🏗️"],
  [/цегл|блок|газоблок|піноблок/i, "🧱"],
  [/вікн|склопакет/i, "🪟"],
  [/двер/i, "🚪"],
  [/дах|покрівл|черепиц|шифер|ондулін|металочерепиц/i, "🏠"],
  [/труб|сантехн|каналізац|водопров/i, "🚰"],
  [/кабель|провід|електрик|розетк|вимикач/i, "🔌"],
  [/фарб|лак|ґрунтовк|грунтовк/i, "🎨"],
  [/плитк|кахель|кераміч/i, "🔲"],
  [/плівк|мембран|гідроізоляц|пароізоляц/i, "🎞️"],
  [/скло/i, "🔷"],
  [/пластик|полікарбонат|пвх|pvc/i, "🧴"],
  [/гіпсокартон|гкл/i, "📋"],
];

export function guessMaterialIcon(name) {
  if (!name) return "";
  const match = RULES.find(([re]) => re.test(name));
  return match ? match[1] : "📦";
}
